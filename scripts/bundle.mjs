/**
 * Bundles the radar into one file, for the desktop build.
 *
 * Normally Node runs the TypeScript sources directly and there is no build step
 * at all — that is the point of the stack. A single executable is the one place
 * that cannot work: Node's SEA support takes one CommonJS file, so the sources
 * have to be flattened first.
 *
 * esbuild is a dev dependency only. It never runs when you use the radar
 * normally, and nothing it produces is needed unless you are packaging.
 */
import { build } from 'esbuild';
import { readdirSync, readFileSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(ROOT, 'build');

mkdirSync(OUT, { recursive: true });

/**
 * The SQL migrations, inlined.
 *
 * At runtime the database reads these from a directory next to the source. A
 * bundle has no directory, so they become part of the code — which also means a
 * missing migration is a build error rather than a mystery at first launch.
 */
function inlineMigrations() {
  const dir = join(ROOT, 'apps', 'api', 'src', 'db', 'migrations');
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort();

  const entries = files
    .map((f) => '  ' + JSON.stringify(f) + ': ' + JSON.stringify(readFileSync(join(dir, f), 'utf8')) + ',')
    .join('\n');

  console.log('  inlined ' + files.length + ' migrations');
  return entries;
}

/**
 * The built dashboard, as a map of path to base64.
 *
 * Base64 rather than raw strings because the bundle also carries fonts and
 * images, and a JS string literal is not a safe home for arbitrary bytes.
 */
function inlineWeb() {
  const dir = join(ROOT, 'apps', 'web', 'dist');
  const files = [];
  let total = 0;

  (function walk(current) {
    for (const name of readdirSync(current)) {
      const full = join(current, name);
      if (statSync(full).isDirectory()) walk(full);
      else files.push(full);
    }
  })(dir);

  const entries = files
    .map((full) => {
      const key = relative(dir, full).split('\\').join('/');
      const data = readFileSync(full);
      total += data.length;
      return '  ' + JSON.stringify(key) + ': ' + JSON.stringify(data.toString('base64')) + ',';
    })
    .join('\n');

  console.log('  inlined ' + files.length + ' dashboard files (' + Math.round(total / 1024) + ' KB)');
  return entries;
}

console.log('Preparing assets');
const migrationEntries = inlineMigrations();
const webEntries = inlineWeb();

/**
 * The generated stand-in for `apps/api/src/embedded.ts`.
 *
 * Written next to the bundle and aliased in below, so the committed stub stays
 * empty and a normal run never sees any of this.
 */
const embedded = join(OUT, 'embedded.generated.js');
writeFileSync(
  embedded,
  [
    '// Generated by scripts/bundle.mjs. Do not edit.',
    'export const MIGRATIONS = {',
    migrationEntries,
    '};',
    'export const WEB_FILES = {',
    webEntries,
    '};',
    'export function isPackaged() { return true; }',
    '',
  ].join('\n'),
);

console.log('Bundling');
const result = await build({
  entryPoints: [join(ROOT, 'apps', 'api', 'src', 'main.ts')],
  bundle: true,
  platform: 'node',
  target: 'node24',
  // SEA takes a single CommonJS file.
  format: 'cjs',
  outfile: join(OUT, 'radar.cjs'),
  // Node builtins stay external; `node:sqlite` is one of them, which is the
  // whole reason this app needs no native module.
  external: ['node:*'],
  // The one substitution that turns a normal build into a packaged one.
  //
  // A plugin rather than `alias`, which only accepts package names. Matching on
  // the filename keeps it working from any importer regardless of how many
  // directories up the relative path went.
  plugins: [
    {
      name: 'embed-assets',
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /(^|[\/])embedded\.ts$/ }, () => ({ path: embedded }));
      },
    },
  ],
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
});

if (result.errors.length > 0) {
  console.error(result.errors);
  process.exit(1);
}

console.log('  build/radar.cjs  ' + Math.round(statSync(join(OUT, 'radar.cjs')).size / 1024) + ' KB');
